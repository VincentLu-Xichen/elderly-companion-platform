#!/usr/bin/env python3
"""Create or validate the Raspberry Pi gateway's private environment file."""

from __future__ import annotations

import argparse
import getpass
import os
import re
import secrets
import subprocess
from pathlib import Path

CONFIG_PATH = Path.home() / ".config" / "esds-voice" / "env"
REQUIRED = ("DASHSCOPE_API_KEY",)
SAFE_VALUE = re.compile(r"^[A-Za-z0-9._:/+-]+$")


def _read_config() -> dict[str, str]:
    if not CONFIG_PATH.is_file():
        return {}
    values: dict[str, str] = {}
    for raw_line in CONFIG_PATH.read_text(encoding="utf-8").splitlines():
        line = raw_line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        values[key.strip()] = value.strip().strip("'\"")
    return values


def _missing(values: dict[str, str]) -> list[str]:
    return [name for name in REQUIRED if not values.get(name, "").strip()]


def _validate_value(name: str, value: str) -> str:
    value = value.strip()
    if not value:
        raise SystemExit(f"{name} 不能为空。")
    if not SAFE_VALUE.fullmatch(value):
        raise SystemExit(f"{name} 含有不支持的字符。")
    return value


def _write_config(values: dict[str, str]) -> None:
    CONFIG_PATH.parent.mkdir(mode=0o700, parents=True, exist_ok=True)
    CONFIG_PATH.parent.chmod(0o700)
    bridge_token = values.get("ESDS_AGENT_BRIDGE_TOKEN") or secrets.token_urlsafe(32)
    bridge_device_id = values.get("ESDS_AGENT_BRIDGE_DEVICE_ID") or (
        "esds-pi-"
        + Path("/etc/machine-id").read_text(encoding="ascii").strip()[:12]
    )
    lines = [
        "# Generated by scripts/configure_pi.py; do not commit this file.",
        "ESDS_RUNTIME_PROVIDER=local",
        "ESDS_ASR_PROVIDER=qwen",
        "ESDS_CHAT_PROVIDER=agent_bridge",
        "ESDS_TTS_PROVIDER=qwen",
        "ESDS_EMOTION_BACKEND=heuristic",
        f"ESDS_QWEN_ASR_REGION={values['ESDS_QWEN_REALTIME_REGION']}",
        f"ESDS_QWEN_TTS_REGION={values['ESDS_QWEN_REALTIME_REGION']}",
        "ESDS_QWEN_TTS_VOICE=Cherry",
        "ESDS_AGENT_BRIDGE_URL=http://127.0.0.1:8000",
        f"ESDS_AGENT_BRIDGE_TOKEN={bridge_token}",
        f"ESDS_AGENT_BRIDGE_DEVICE_ID={bridge_device_id}",
        "ESDS_AGENT_BRIDGE_TIMEOUT_SECONDS=65",
        f"DASHSCOPE_API_KEY={values['DASHSCOPE_API_KEY']}",
        "ESDS_PI_CAPTURE_GAIN=128",
        "ESDS_PI_AUTO_GAIN_MAX_DB=18",
        "ESDS_PI_AUTO_GAIN_TARGET_DBFS=-20",
        "ESDS_PI_PLAYBACK_VOLUME=800",
        "ESDS_VAD_START_DBFS=-48",
        "ESDS_VAD_STOP_DBFS=-54",
        "ESDS_VAD_START_SNR_DB=12",
        "ESDS_VAD_STOP_SNR_DB=6",
        "ESDS_LOG_LEVEL=INFO",
        "",
    ]
    temporary = CONFIG_PATH.with_suffix(".tmp")
    descriptor = os.open(
        temporary,
        os.O_WRONLY | os.O_CREAT | os.O_TRUNC,
        0o600,
    )
    with os.fdopen(descriptor, "w", encoding="utf-8") as output:
        output.write("\n".join(lines))
    temporary.chmod(0o600)
    temporary.replace(CONFIG_PATH)
    CONFIG_PATH.chmod(0o600)


def _restart_service() -> None:
    completed = subprocess.run(
        [
            "systemctl",
            "--user",
            "restart",
            "elderly-agent.service",
            "esds-voice.service",
            "esds-pi-audio.service",
        ],
        check=False,
    )
    if completed.returncode:
        print(
            "配置已保存；服务尚未启动。请运行："
            "systemctl --user restart esds-voice.service"
        )
    else:
        print("配置已保存，ESDS 网关和原生音频客户端已重启。")


def configure() -> None:
    print(
        "ESDS 百炼配置已启动。输入 API Key 时终端不会显示任何字符，"
        "输入完成后按回车。",
        flush=True,
    )
    current = _read_config()
    existing_key = current.get("DASHSCOPE_API_KEY", "")
    key_prompt = "百炼 DASHSCOPE API Key"
    if existing_key:
        key_prompt += "（回车保留现有值）"
    key = getpass.getpass(f"{key_prompt}: ").strip() or existing_key

    region_default = current.get(
        "ESDS_QWEN_ASR_REGION",
        current.get("ESDS_QWEN_REALTIME_REGION", "beijing"),
    )
    region = input(
        f"区域 beijing/singapore（默认 {region_default}）: "
    ).strip() or region_default
    if region not in {"beijing", "singapore"}:
        raise SystemExit("区域只能是 beijing 或 singapore。")

    values = {
        "DASHSCOPE_API_KEY": _validate_value("DASHSCOPE_API_KEY", key),
        "ESDS_QWEN_REALTIME_REGION": region,
        "ESDS_AGENT_BRIDGE_TOKEN": current.get("ESDS_AGENT_BRIDGE_TOKEN", ""),
        "ESDS_AGENT_BRIDGE_DEVICE_ID": current.get(
            "ESDS_AGENT_BRIDGE_DEVICE_ID", ""
        ),
    }
    _write_config(values)
    _restart_service()


def check() -> int:
    values = _read_config()
    missing = _missing(values)
    if missing:
        print(
            "ESDS 配置未完成，缺少：" + ", ".join(missing),
            flush=True,
        )
        return 1
    required_profile = {
        "ESDS_RUNTIME_PROVIDER": "local",
        "ESDS_ASR_PROVIDER": "qwen",
        "ESDS_TTS_PROVIDER": "qwen",
    }
    problems = [
        name
        for name, expected in required_profile.items()
        if values.get(name) != expected
    ]
    if values.get("ESDS_CHAT_PROVIDER") not in {
        "agent_bridge",
        "cbt_agent_bridge",
    }:
        problems.append("ESDS_CHAT_PROVIDER")
    problems.extend(
        name
        for name in ("ESDS_AGENT_BRIDGE_TOKEN", "ESDS_AGENT_BRIDGE_DEVICE_ID")
        if not values.get(name)
    )
    if problems:
        print(
            "ESDS Daily Chat 集成配置不完整：" + ", ".join(problems),
            flush=True,
        )
        return 1
    return 0


def apply_audio_profile() -> None:
    values = _read_config()
    missing = _missing(values)
    if missing:
        raise SystemExit("ESDS 配置未完成，缺少：" + ", ".join(missing))
    values.setdefault(
        "ESDS_QWEN_REALTIME_REGION",
        values.get("ESDS_QWEN_ASR_REGION", "beijing"),
    )
    _write_config(values)
    _restart_service()


def main() -> None:
    parser = argparse.ArgumentParser(
        description="配置树莓派上的 ESDS 百炼实时语音服务"
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="只验证配置是否完整，不读取或显示密钥",
    )
    parser.add_argument(
        "--apply-audio-profile",
        action="store_true",
        help="保留现有凭据并应用创乐博模块的音频标定参数",
    )
    args = parser.parse_args()
    if args.check:
        raise SystemExit(check())
    if args.apply_audio_profile:
        apply_audio_profile()
        return
    configure()


if __name__ == "__main__":
    main()
